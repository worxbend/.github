/**
 * fx/nebula.js — the hero's nebula: a slow, luminous cloud drawn with PixiJS into a small canvas
 * that sits inside the hero, where the terminal-style readout used to be.
 *
 * Contract, matching the other two effect layers (SPEC.md §4):
 *   mountNebula(canvas, { palette }) -> Promise<{ dispose, setPalette } | null>
 *
 * The whole layer is decoration. If anything at all goes wrong — the content delivery network
 * serving PixiJS is unreachable, the browser cannot give us a rendering context, the canvas has
 * no size — this module resolves to `null` and the page carries on without it. Nothing here is
 * allowed to throw into the caller.
 *
 * How the cloud is made
 * ---------------------
 * There is no noise shader here, on purpose: a hand-written fragment shader is the one part of
 * PixiJS whose API has changed with every major version, and this layer must fail soft rather
 * than interestingly. Instead the nebula is built the way stage smoke is: a handful of large,
 * very soft radial-gradient sprites ("puffs"), tinted from the theme's scene palette, drawn with
 * additive blending so overlaps glow, each drifting and breathing on its own slow sine phase. A
 * dozen of them layered over a few pin-prick stars reads as one organic cloud, and it costs a
 * few sprite transforms per frame instead of a full-screen shader pass.
 *
 * Everything is seeded, so the cloud has the same shape on every visit — like the sky behind it,
 * it is meant to be a place, not a lottery.
 */

import { motion } from '../core/motion.js';

// Dynamic for the same reason as in glyphs.js: a static import that fails to resolve takes the
// whole module down before mountNebula() can run, and the failure must land in a catch instead.
const loadPixi = () => import('pixi.js');

/** How many gradient puffs make up the cloud. Enough to read as one mass, cheap enough to forget. */
const PUFF_COUNT = 14;

/** How many pin-prick stars twinkle inside the cloud. */
const STAR_COUNT = 26;

/** The gradient texture's edge, in device pixels. One texture is shared by every puff. */
const PUFF_TEX_SIZE = 256;

/** Slowest and fastest full drift cycles, in seconds. Nothing here should look busy. */
const CYCLE_MIN_S = 14;
const CYCLE_MAX_S = 26;

/** Milliseconds to wait after the last resize before re-laying the cloud out. */
const RESIZE_DEBOUNCE_MS = 150;

/** Deterministic pseudo-random generator (mulberry32), same as the other layers. */
function makeRandom(seed) {
  let a = seed >>> 0;
  return () => {
    a += 0x6d2b79f5;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** '#8AB4FF' -> 0x8ab4ff, with a quiet fallback for a token that failed to resolve. */
function hexToNumber(hex, fallback) {
  const text = String(hex || '').trim().replace(/^#/, '');
  const full = text.length === 3 ? text.replace(/./g, (c) => c + c) : text;
  const n = Number.parseInt(full, 16);
  return Number.isFinite(n) && full.length === 6 ? n : fallback;
}

/**
 * The one shared texture: a radial falloff from soft white to transparent.
 *
 * Drawn once on a plain 2D canvas rather than generated by PixiJS, because a gradient is the one
 * thing the 2D API does better than a sprite renderer. The falloff is deliberately gentler than
 * a linear gradient — three stops, easing out — so a puff has no visible rim; a hard edge is what
 * makes cheap smoke look cheap.
 */
function makePuffTexture(PIXI) {
  const canvas = document.createElement('canvas');
  canvas.width = PUFF_TEX_SIZE;
  canvas.height = PUFF_TEX_SIZE;
  const ctx = canvas.getContext('2d');
  if (!ctx) return null;
  const half = PUFF_TEX_SIZE / 2;
  const gradient = ctx.createRadialGradient(half, half, 0, half, half, half);
  gradient.addColorStop(0, 'rgba(255,255,255,0.85)');
  gradient.addColorStop(0.35, 'rgba(255,255,255,0.32)');
  gradient.addColorStop(0.7, 'rgba(255,255,255,0.08)');
  gradient.addColorStop(1, 'rgba(255,255,255,0)');
  ctx.fillStyle = gradient;
  ctx.fillRect(0, 0, PUFF_TEX_SIZE, PUFF_TEX_SIZE);
  return PIXI.Texture.from(canvas);
}

/** Relative luminance of a 0xRRGGBB number, 0 (black) to 1 (white). Rough is fine here. */
function luminance(tint) {
  const r = (tint >> 16) & 0xff;
  const g = (tint >> 8) & 0xff;
  const b = tint & 0xff;
  return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
}

/**
 * The colours a palette offers this layer, in the order puffs cycle through them.
 *
 * Deliberately only the saturated middle of the scene palette, and never anything pale: under
 * additive blending a dozen overlapping near-white puffs sum to a grey haze, which is exactly
 * what the first build of this layer looked like. Any candidate lighter than the ceiling is
 * swapped for the link colour — that guard is what keeps the solar theme working, whose scene
 * "fog" is pale sky rather than deep space. The only white on the stage is the pin-prick stars,
 * which is what makes them read as stars.
 */
function puffTints(palette) {
  const link = hexToNumber(palette.link, 0x2b4a9e);
  const usable = (hex, fallback) => {
    const tint = hexToNumber(hex, fallback);
    return luminance(tint) > 0.7 ? link : tint;
  };
  return [
    usable(palette.fog, 0x101a3a),
    usable(palette.starB, 0x4c7dff),
    link,
    usable(palette.glyph, 0x4c7dff),
    usable(palette.fog, 0x101a3a),
    link,
  ];
}

export async function mountNebula(canvas, { palette } = {}) {
  if (!canvas || !canvas.parentElement) return null;

  let PIXI;
  try {
    PIXI = await loadPixi();
  } catch {
    return null;
  }

  const host = canvas.parentElement;
  const app = new PIXI.Application();
  try {
    await app.init({
      canvas,
      backgroundAlpha: 0,
      antialias: true,
      resolution: Math.min(window.devicePixelRatio || 1, 2),
      autoDensity: true,
      // The frame loop belongs to core/motion.js; PixiJS only renders when told to.
      autoStart: false,
      sharedTicker: false,
    });
  } catch {
    return null;
  }
  app.ticker.stop();

  const texture = makePuffTexture(PIXI);
  if (!texture) {
    app.destroy();
    return null;
  }

  const random = makeRandom(0x77626e62); // 'wbnb'
  const puffs = [];
  const stars = [];
  let width = 0;
  let height = 0;

  /**
   * One puff: a sprite plus the constants of its private orbit. The drift is two incommensurate
   * sine phases rather than a velocity, so a puff wanders inside its home region forever without
   * needing wrap-around or respawn logic — and a paused tab resumes exactly in phase.
   */
  function makePuff(index, tints) {
    const sprite = new PIXI.Sprite(texture);
    sprite.anchor.set(0.5);
    sprite.blendMode = 'add';
    sprite.tint = tints[index % tints.length];

    // The puffs are not scattered — they are strung along a spine that meanders across the band,
    // with jitter around it. Uniform scatter was tried first and additive blending summed it into
    // one even wash that filled the frame edge to edge; a nebula needs dark space around it to
    // read as a cloud at all. The spine gives the mass one continuous, wisp-like shape, and the
    // taper below thins it out toward both ends.
    const along = PUFF_COUNT === 1 ? 0.5 : index / (PUFF_COUNT - 1);
    const spineY = 0.5 + Math.sin(along * Math.PI * 1.7 + 0.6) * 0.24;
    // 1 in the middle of the band, approaching 0 at the ends.
    const taper = Math.sin(along * Math.PI);

    const puff = {
      sprite,
      // Home position as a fraction of the stage, so a resize only rescales, never reshuffles.
      hx: along * 0.96 + 0.02 + (random() - 0.5) * 0.08,
      hy: spineY + (random() - 0.5) * 0.22,
      // The wander radius, also fractional. Small: the cloud shimmers, it does not migrate.
      rx: 0.03 + random() * 0.06,
      ry: 0.05 + random() * 0.1,
      // Base scale relative to the stage height, thinning toward the spine's ends.
      size: (0.55 + random() * 0.9) * (0.45 + 0.75 * taper),
      phase: random() * Math.PI * 2,
      speed: (Math.PI * 2) / (CYCLE_MIN_S + random() * (CYCLE_MAX_S - CYCLE_MIN_S)),
      alpha: (0.22 + random() * 0.2) * (0.5 + 0.5 * taper),
    };
    app.stage.addChild(sprite);
    return puff;
  }

  function makeStar() {
    const sprite = new PIXI.Sprite(texture);
    sprite.anchor.set(0.5);
    sprite.blendMode = 'add';
    sprite.tint = 0xffffff;
    const star = {
      sprite,
      hx: 0.02 + random() * 0.96,
      hy: 0.08 + random() * 0.84,
      size: 0.02 + random() * 0.035,
      phase: random() * Math.PI * 2,
      speed: (Math.PI * 2) / (2.5 + random() * 5),
      alpha: 0.35 + random() * 0.45,
    };
    app.stage.addChild(sprite);
    return star;
  }

  function layout() {
    const rect = host.getBoundingClientRect();
    width = Math.max(1, Math.round(rect.width));
    height = Math.max(1, Math.round(rect.height));
    app.renderer.resize(width, height);
    for (const puff of puffs) {
      puff.sprite.position.set(puff.hx * width, puff.hy * height);
      const scale = (puff.size * height) / (PUFF_TEX_SIZE / 2);
      puff.sprite.scale.set(scale * 1.6, scale);
    }
    for (const star of stars) {
      star.sprite.position.set(star.hx * width, star.hy * height);
      const scale = Math.max(0.02, (star.size * height) / (PUFF_TEX_SIZE / 2));
      star.sprite.scale.set(scale);
    }
  }

  const tints = puffTints(palette || {});
  for (let i = 0; i < PUFF_COUNT; i += 1) puffs.push(makePuff(i, tints));
  for (let i = 0; i < STAR_COUNT; i += 1) stars.push(makeStar());
  layout();

  let elapsed = 0;

  function frame(dt) {
    // Reduced motion holds the cloud still but keeps it painted: the visitor asked for less
    // movement, not for a blank rectangle. `elapsed` simply stops advancing.
    if (!motion.reduced) elapsed += dt;
    for (const puff of puffs) {
      const t = elapsed * puff.speed + puff.phase;
      puff.sprite.x = (puff.hx + Math.sin(t) * puff.rx) * width;
      puff.sprite.y = (puff.hy + Math.sin(t * 1.31 + 1.7) * puff.ry) * height;
      puff.sprite.alpha = puff.alpha * (0.8 + 0.2 * Math.sin(t * 0.63 + 0.4));
    }
    for (const star of stars) {
      const t = elapsed * star.speed + star.phase;
      star.sprite.alpha = star.alpha * (0.55 + 0.45 * Math.sin(t));
    }
    app.renderer.render(app.stage);
  }

  const removeFrame = motion.add(frame);

  let resizeTimer = 0;
  const onResize = () => {
    window.clearTimeout(resizeTimer);
    resizeTimer = window.setTimeout(layout, RESIZE_DEBOUNCE_MS);
  };
  window.addEventListener('resize', onResize);

  // Paint the first frame immediately, so the cloud is there before the loop's first tick —
  // and stays there permanently if the visitor prefers reduced motion.
  frame(0);

  return {
    setPalette(next) {
      const nextTints = puffTints(next || {});
      puffs.forEach((puff, index) => {
        puff.sprite.tint = nextTints[index % nextTints.length];
      });
      frame(0);
    },
    dispose() {
      removeFrame();
      window.removeEventListener('resize', onResize);
      window.clearTimeout(resizeTimer);
      // `texture: true` releases the shared gradient texture along with the sprites.
      app.destroy(false, { children: true, texture: true });
    },
  };
}
